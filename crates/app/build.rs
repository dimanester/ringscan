//! Build script: Windows resources for `ringscan.exe`.
//!
//! When the target is Windows it
//! 1. rasterizes the logo from `src/icon_art.rs` (the same code the app uses
//!    for its window icon) at 16, 24, 32, 48, 64 and 256 px and writes a
//!    multi-size `.ico` into `OUT_DIR` (BMP entries below 256 px for maximum
//!    compatibility, a PNG entry at 256 px),
//! 2. writes a resource script with that icon, the application manifest
//!    (`assets/ringscan.manifest`) and a VERSIONINFO block,
//! 3. compiles it with mingw's `windres` into a COFF object and links that
//!    object into the binary.
//!
//! Override the resource compiler with the `RINGSCAN_WINDRES` environment
//! variable. Other targets get no resources.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

#[path = "src/icon_art.rs"]
mod icon_art;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src/icon_art.rs");
    println!("cargo:rerun-if-changed=assets/ringscan.manifest");
    println!("cargo:rerun-if-env-changed=RINGSCAN_WINDRES");
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("windows") {
        return;
    }
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));

    let ico = out.join("ringscan.ico");
    fs::write(&ico, build_ico(&[16, 24, 32, 48, 64, 256])).expect("write ico");

    let manifest = manifest_dir.join("assets").join("ringscan.manifest");
    let rc = out.join("ringscan.rc");
    fs::write(&rc, resource_script(&ico, &manifest)).expect("write rc");

    let obj = out.join("ringscan-res.o");
    let windres = env::var("RINGSCAN_WINDRES").unwrap_or_else(|_| default_windres());
    let status = Command::new(&windres)
        .arg("--input")
        .arg(&rc)
        .arg("--output-format=coff")
        .arg("--output")
        .arg(&obj)
        .status()
        .unwrap_or_else(|e| panic!("cannot run {windres}: {e}"));
    assert!(status.success(), "{windres} failed: {status}");
    // Linking the object directly (not via a static library) keeps the
    // linker from dropping it as unreferenced.
    println!("cargo:rustc-link-arg-bins={}", obj.display());
}

/// `windres` matching the target: `x86_64-w64-mingw32-windres` for the gnu
/// cross target, plain `windres` otherwise.
fn default_windres() -> String {
    let arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    match (arch.as_str(), env::var("CARGO_CFG_TARGET_ENV").as_deref()) {
        ("x86_64", Ok("gnu")) => "x86_64-w64-mingw32-windres".into(),
        ("x86", Ok("gnu")) => "i686-w64-mingw32-windres".into(),
        _ => "windres".into(),
    }
}

/// The `.rc` text. Paths are quoted with forward slashes, which windres
/// accepts on every host.
fn resource_script(ico: &Path, manifest: &Path) -> String {
    let version = env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    let mut parts: Vec<u16> = version.split('.').map(|p| p.parse().unwrap_or(0)).collect();
    parts.resize(4, 0);
    let commas = format!("{},{},{},{}", parts[0], parts[1], parts[2], parts[3]);
    let path = |p: &Path| p.display().to_string().replace('\\', "/");
    format!(
        r#"// Generated by build.rs; do not edit.
1 ICON "{ico}"
1 24 "{manifest}"
1 VERSIONINFO
FILEVERSION {commas}
PRODUCTVERSION {commas}
FILEOS 0x40004
FILETYPE 0x1
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "RingScan contributors"
      VALUE "FileDescription", "RingScan disk usage visualizer"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "ringscan"
      VALUE "LegalCopyright", "MIT License"
      VALUE "OriginalFilename", "ringscan.exe"
      VALUE "ProductName", "RingScan"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#,
        ico = path(ico),
        manifest = path(manifest),
    )
}

/// A `.ico` file with one 32-bit entry per size.
fn build_ico(sizes: &[u32]) -> Vec<u8> {
    let images: Vec<(u32, Vec<u8>)> = sizes
        .iter()
        .map(|&s| {
            let rgba = icon_art::render(s);
            let data = if s >= 256 {
                png_bytes(s, &rgba)
            } else {
                bmp_dib(s, &rgba)
            };
            (s, data)
        })
        .collect();
    let mut out = Vec::new();
    // ICONDIR
    out.extend_from_slice(&0u16.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&(images.len() as u16).to_le_bytes());
    let mut offset = 6 + 16 * images.len() as u32;
    for (s, data) in &images {
        // ICONDIRENTRY: 0 means 256 for width/height.
        let dim = if *s >= 256 { 0 } else { *s as u8 };
        out.push(dim);
        out.push(dim);
        out.push(0); // palette colors
        out.push(0); // reserved
        out.extend_from_slice(&1u16.to_le_bytes()); // planes
        out.extend_from_slice(&32u16.to_le_bytes()); // bits per pixel
        out.extend_from_slice(&(data.len() as u32).to_le_bytes());
        out.extend_from_slice(&offset.to_le_bytes());
        offset += data.len() as u32;
    }
    for (_, data) in &images {
        out.extend_from_slice(data);
    }
    out
}

/// A 32-bit BGRA DIB with an AND mask, as stored inside `.ico` files.
fn bmp_dib(size: u32, rgba: &[u8]) -> Vec<u8> {
    let n = size as usize;
    let mask_row = n.div_ceil(32) * 4;
    let mut out = Vec::with_capacity(40 + n * n * 4 + mask_row * n);
    // BITMAPINFOHEADER; the height counts the color and the mask bitmaps.
    out.extend_from_slice(&40u32.to_le_bytes());
    out.extend_from_slice(&(size as i32).to_le_bytes());
    out.extend_from_slice(&(2 * size as i32).to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes());
    out.extend_from_slice(&32u16.to_le_bytes());
    out.extend_from_slice(&0u32.to_le_bytes()); // BI_RGB
    out.extend_from_slice(&((n * n * 4 + mask_row * n) as u32).to_le_bytes());
    out.extend_from_slice(&[0u8; 16]); // resolution, palette
    // Bottom-up rows.
    for y in (0..n).rev() {
        for x in 0..n {
            let i = (y * n + x) * 4;
            out.extend_from_slice(&[rgba[i + 2], rgba[i + 1], rgba[i], rgba[i + 3]]);
        }
    }
    // AND mask: 1 = transparent (only used by legacy renderers).
    for y in (0..n).rev() {
        let mut row = vec![0u8; mask_row];
        for x in 0..n {
            if rgba[(y * n + x) * 4 + 3] == 0 {
                row[x / 8] |= 0x80 >> (x % 8);
            }
        }
        out.extend_from_slice(&row);
    }
    out
}

fn png_bytes(size: u32, rgba: &[u8]) -> Vec<u8> {
    let mut buf = Vec::new();
    {
        let mut enc = png::Encoder::new(&mut buf, size, size);
        enc.set_color(png::ColorType::Rgba);
        enc.set_depth(png::BitDepth::Eight);
        enc.set_compression(png::Compression::High);
        let mut w = enc.write_header().expect("png header");
        w.write_image_data(rgba).expect("png data");
    }
    buf
}
